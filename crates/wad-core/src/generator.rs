//! The files wadd writes for a workspace: its quadlet unit
//! (`wad-<id>.container`, which the registry installs; three files while
//! it's streamed: stream_quadlets), and WadBrowser's
//! config (`/etc/wadspaces/wadbrowser.conf`: what links open in), which the
//! layers' build folders carry (layers.rs). Project files are never in an
//! image: a wadspace takes them in when it starts, or wadd mounts them.

use serde_json::Value;

use crate::js;

/// A shell-safe double-quoted string (Dockerfile ENV and RUN arguments).
pub(crate) fn q(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        if matches!(c, '"' | '\\' | '$' | '`') {
            out.push('\\');
        }
        out.push(c);
    }
    out.push('"');
    out
}

/// /etc/wadspaces/wadbrowser.conf for a design with a WadBrowser on its
/// desktop: links open in that one.
pub fn wadbrowser_conf(spec: &Value) -> Option<String> {
    let mode = spec.get("defaultBrowser").and_then(Value::as_str).filter(|m| matches!(*m, "full" | "focus"))?;
    Some(format!(
        "# WadBrowser's settings for this workspace, from its WadSpaces Client design (a\n\
         # user's own go in ~/.config/wadbrowser/wadbrowser.conf).\n\
         #\n\
         # What links open in: full (tabs and an address bar) or focus (no address bar).\n\
         default = {mode}\n"
    ))
}

/// Where wadd keeps each workspace's extra folder (projects.json and the
/// rest) and the copies wadspaces take in.
pub const STATE_DIR: &str = "/var/lib/wadspaces";
/// Where a wadspace sees the copies it takes in: `<COPIES_ROOT>/<project id>`.
pub const COPIES_ROOT: &str = "/run/wadspaces-copies";

/// Rootless podman (wadd under your own systemd, on a laptop): the
/// container's root is you and its uid 1000 a subordinate id, so abc (PUID
/// 1000) couldn't write the folders you own (a sign-in's). These maps put
/// you at uid 1000 inside instead and keep the rest of the usual 65536 ids.
/// (keep-id would too, but its passwd entry stops the image's init moving
/// abc onto that uid.)
const SUBORDINATE_IDS: u32 = 65536;

fn id_maps(uid: u32) -> Vec<String> {
    let ranges =
        [format!("0:1:{uid}"), format!("{uid}:0:1"), format!("{}:{}:{}", uid + 1, uid + 1, SUBORDINATE_IDS - uid - 1)];
    ranges.iter().map(|r| format!("UIDMap={r}")).chain(ranges.iter().map(|r| format!("GIDMap={r}"))).collect()
}

/// wadd's quadlet unit for a workspace (wad-<id>.container). `rootless_uid`:
/// the host user to map to uid 1000 inside (rootless podman only).
pub fn quadlet(w: &Value, state_dir: &str, rootless_uid: Option<u32>) -> String {
    workspace_unit(&one_line(w), state_dir, rootless_uid, None)
}

/// The sidecar's port the stream is served on (nginx, plain HTTP: wadd's
/// proxy and the tunnel in front of it end TLS).
pub const STREAM_PORT: u16 = 3000;

/// A streamed wadspace's files (name, text): its unit, drawing on its
/// sidecar's display instead of the screen and going with it; the sidecar
/// (`stream.image`: Selkies, its compositor, its web client behind a
/// login); and the display volume they share. `stream`: { guid, web_port,
/// mux_port, user, image, webrtc, turn_token_id }. The password is podman
/// secret `wad_stream_<id>` (nginx asks for it on every path, the page and
/// the websocket); the sidecar won't start without it. Its web port is
/// published on 127.0.0.1 only: wadd's streaming proxy is the way in.
/// WebRTC (STUN, Cloudflare's TURN, the mux port) only with `webrtc`.
pub fn stream_quadlets(w: &Value, stream: &Value, state_dir: &str, rootless_uid: Option<u32>) -> Vec<(String, String)> {
    let (w, stream) = (&one_line(w), &one_line(stream));
    let id = js::field(w, "id");
    let display = format!("wad-{id}-display");
    let workspace = workspace_unit(w, state_dir, rootless_uid, Some(&display));
    let env = w.get("env").and_then(Value::as_object).cloned().unwrap_or_default();
    let mut lines: Vec<String> = vec![
        "# Generated by wadd: the stream a wadspace draws on while it's streamed. Do not edit.".into(),
        "[Unit]".into(),
        format!("Description=WadSpaces stream: {}", js::field(w, "name")),
        // Its wadspace binds it: they start and stop together.
        "StopWhenUnneeded=yes".into(),
        String::new(),
        "[Container]".into(),
        format!("Image={}", js::field(stream, "image")),
        format!("ContainerName={display}"),
        format!("Label=wadspaces.id={id}"),
        "Label=wadspaces.role=display".into(),
        format!("Label=wadspaces.stream={}", js::field(stream, "guid")),
    ];
    if let Some(uid) = rootless_uid {
        lines.extend(id_maps(uid));
    }
    lines.push(env_line("CUSTOM_USER", &js::field(stream, "user")));
    for k in ["PGID", "PUID", "TZ"] {
        if let Some(v) = env.get(k) {
            lines.push(env_line(k, &js::string(v)));
        }
    }
    // WebSockets first: the transport that always works, through the tunnel.
    lines.push(env_line("SELKIES_MODE", "websockets"));
    lines.push(env_line("TITLE", &js::field(w, "name")));
    let mux = js::field(stream, "mux_port");
    let webrtc = stream.get("webrtc").is_some_and(js::truthy);
    if webrtc {
        // Never a public IP or ICE-lite: the machine has no address a
        // browser can reach; media goes through Cloudflare's TURN.
        for (k, v) in [
            ("SELKIES_ENABLE_DUAL_MODE", "true".to_string()),
            ("SELKIES_WEBRTC_UDP_MUX_PORT", mux.clone()),
            ("SELKIES_WEBRTC_TCP_MUX_PORT", mux.clone()),
            ("SELKIES_STUN_HOST", "stun.cloudflare.com".into()),
            ("SELKIES_STUN_PORT", "3478".into()),
            ("SELKIES_ENABLE_CLOUDFLARE_TURN", "true".into()),
            ("SELKIES_CLOUDFLARE_TURN_TOKEN_ID", js::field(stream, "turn_token_id")),
        ] {
            lines.push(env_line(k, &v));
        }
    }
    lines.push(format!("Secret=wad_stream_{id},type=env,target=PASSWORD"));
    if webrtc {
        lines.push("Secret=wad_turn_api_token,type=env,target=SELKIES_CLOUDFLARE_TURN_API_TOKEN".into());
    }
    lines.push(format!("Volume={display}.volume:/run/wadspaces-display:z"));
    lines.push(format!("PublishPort=127.0.0.1:{}:{STREAM_PORT}", js::field(stream, "web_port")));
    if webrtc {
        lines.push(format!("PublishPort={mux}:{mux}/udp"));
        lines.push(format!("PublishPort={mux}:{mux}/tcp"));
    }
    if js::strs(w, "devices").iter().any(|d| d == "/dev/dri") {
        lines.push("AddDevice=/dev/dri".into());
    }
    if let Some(s) = w.get("shm_size").filter(|s| js::truthy(s)) {
        lines.push(format!("ShmSize={}", js::string(s)));
    }
    // 900 s as a workspace: rootless podman copies a whole image the first
    // time it maps its uids (minutes for this one).
    for l in ["Pull=never", "", "[Service]", "Restart=no", "TimeoutStartSec=900", ""] {
        lines.push(l.into());
    }
    // Owned by abc (1000): a plain volume is root's each time it's mounted,
    // which locked the sidecar out of its own socket.
    let volume = [
        "# Generated by wadd: the display a streamed wadspace and its sidecar share.",
        "[Volume]",
        &format!("VolumeName={display}"),
        "User=1000",
        "Group=1000",
        "",
    ]
    .join("\n");
    vec![
        (format!("wad-{id}.container"), workspace),
        (format!("{display}.container"), lines.join("\n")),
        (format!("{display}.volume"), volume),
    ]
}

/// An `Environment=` line systemd reads back as exactly `k=v`: quoted when
/// the value has spaces, quotes or backslashes (systemd would split it, or
/// eat them), and `%` doubled (a specifier otherwise).
fn env_line(k: &str, v: &str) -> String {
    let v = v.replace('%', "%%");
    if v.chars().any(|c| c.is_whitespace() || matches!(c, '"' | '\'' | '\\')) {
        format!("Environment=\"{k}={}\"", v.replace('\\', "\\\\").replace('"', "\\\""))
    } else {
        format!("Environment={k}={v}")
    }
}

/// The spec with every text on one line: control characters in a value (a
/// name, an env value) become spaces, so no value can add lines of its own
/// to a unit. (wadd refuses such values before they get here, too.)
fn one_line(v: &Value) -> Value {
    match v {
        Value::String(s) => Value::String(s.chars().map(|c| if c.is_control() { ' ' } else { c }).collect()),
        Value::Array(a) => Value::Array(a.iter().map(one_line).collect()),
        Value::Object(m) => Value::Object(
            m.iter().map(|(k, x)| (k.chars().filter(|c| !c.is_control()).collect(), one_line(x))).collect(),
        ),
        other => other.clone(),
    }
}

/// The workspace's unit. `display`: its stream sidecar's name, while it's
/// streamed (it draws on that sidecar's display, not the screen).
fn workspace_unit(w: &Value, state_dir: &str, rootless_uid: Option<u32>, display: Option<&str>) -> String {
    let native = w.get("display").and_then(Value::as_str) == Some("host");
    let id = js::field(w, "id");
    let container_name = match w.get("container_name").filter(|c| js::truthy(c)) {
        Some(c) => js::string(c),
        None => format!("wad-{id}"),
    };
    let mut lines: Vec<String> = vec![
        "# Generated by `wadd gen-quadlets` from workspaces.yaml. Do not edit.".into(),
        "[Unit]".into(),
        format!("Description=WadSpaces workspace: {}", js::field(w, "name")),
        "Wants=network-online.target".into(),
        "After=network-online.target".into(),
    ];
    // Streamed: its sidecar starts first, and when the sidecar stops (or
    // dies) so does it.
    if let Some(d) = display {
        lines.push(format!("BindsTo={d}.service"));
        lines.push(format!("After={d}.service"));
    }
    lines.extend([
        String::new(),
        "[Container]".into(),
        format!("Image={}", js::field(w, "image")),
        format!("ContainerName={container_name}"),
        format!("Label=wadspaces.id={id}"),
    ]);
    if let Some(uid) = rootless_uid {
        lines.extend(id_maps(uid));
    }
    if !native {
        let cport = js::present(w, "container_port").map(js::string).unwrap_or_else(|| "3000".into());
        lines.push(format!("PublishPort=127.0.0.1:{}:{cport}", js::field(w, "port")));
    }
    let env = w.get("env").and_then(Value::as_object).cloned().unwrap_or_default();
    let mut keys: Vec<&String> = env.keys().collect();
    keys.sort_by(|a, b| js::cmp16(a, b));
    for k in keys {
        lines.push(env_line(k, &js::string(&env[k.as_str()])));
    }
    for s in js::strs(w, "secrets") {
        lines.push(format!("Secret={s}"));
    }
    for v in js::strs(w, "volumes") {
        lines.push(format!("Volume={v}"));
    }
    // A GitHub project or a copy isn't mounted: the wadspace clones it, or
    // copies it in, into its own /config. What it copies from is wadd's copy
    // of the files, read-only (a copy's, or a GitHub project's clone from when
    // wadd kept them on the machine, for it to start from). A mount is the
    // machine's own folder or file (`path`, which wadd found here; none: not
    // on this machine), read-write and never relabelled (no :z: it's the
    // user's), so the container runs without SELinux separation.
    let mut mounted = false;
    for p in js::arr(w, "projects") {
        let id = js::field(p, "id");
        if js::field(p, "kind") == "mount" {
            if let Some(path) = p.get("path").filter(|x| js::truthy(x)) {
                lines.push(format!("Volume={}:/config/Desktop/{}:rw", js::string(path), js::field(p, "mount")));
                mounted = true;
            }
            continue;
        }
        lines.push(format!("Volume={state_dir}/copies/{id}:{COPIES_ROOT}/{id}:ro,z"));
    }
    // Saved sign-ins: each its folder on the host (`path`, wadd's), read-write
    // and shared with the other wadspaces that use it (:z, not :Z).
    let signins = js::arr(w, "signins");
    for s in signins.iter().filter(|s| s.get("path").is_some_and(js::truthy)) {
        let path = js::string(&s["path"]);
        lines.push(format!("Volume={path}:{}/{}:rw,z", crate::signins::MOUNT_ROOT, js::field(s, "id")));
    }
    // Its extra folder, always: projects.json, signins.json and the wallpaper
    // it's started with (a wadspace's is handed over, not in its image).
    lines.push(format!("Volume={state_dir}/extra/{id}:/run/wadspaces-extra:ro,z"));
    // The kiosk session's sway (uid 1000) is the compositor it draws on, or
    // while it's streamed, its sidecar's.
    if native {
        match display {
            Some(d) => lines.push(format!("Volume={d}.volume:/run/wadspaces-display:z")),
            None => lines.push("Volume=/run/user/1000:/run/wadspaces-display".into()),
        }
        // Sound: the session's PipeWire, through its PulseAudio socket in
        // the same runtime dir (the sidecar's pulseaudio opens one there too).
        lines.push("Environment=PULSE_SERVER=unix:/run/wadspaces-display/pulse/native".into());
    }
    // The screen's runtime dir can't be relabelled; a stream's display
    // volume is (:z, shared with its sidecar).
    if (native && display.is_none()) || mounted {
        lines.push("SecurityLabelDisable=true".into());
    }
    for d in js::strs(w, "devices") {
        lines.push(format!("AddDevice={d}"));
    }
    // Devices wadd can attach while it runs (USB, gamepads, webcams, serial,
    // security keys): their nodes may be opened, not made ("rw", no "m";
    // wadd makes them, apps/wadd/src/devices).
    for r in js::strs(w, "device_rules") {
        lines.push(format!("PodmanArgs=\"--device-cgroup-rule={r}\""));
    }
    // Its ~/Drives: the drives wadd binds into this folder on the machine,
    // followed as they come and go (rslave), running or not.
    if let Some(d) = w.get("drives_dir").filter(|d| js::truthy(d)) {
        lines.push(format!("Volume={}:/config/Drives:rslave", js::string(d)));
    }
    if let Some(s) = w.get("shm_size").filter(|s| js::truthy(s)) {
        lines.push(format!("ShmSize={}", js::string(s)));
    }
    for l in [
        "Pull=missing",
        "",
        "[Service]",
        "Restart=no",
        "TimeoutStartSec=900",
        "",
        "# No [Install] section: wadd starts this unit on the first switch.",
        "",
    ] {
        lines.push(l.into());
    }
    lines.join("\n")
}

#[cfg(test)]
mod tests {
    use serde_json::json;

    #[test]
    fn rootless_units_match_the_python_wadd() {
        let w = json!({
            "id": "writing", "name": "Writing", "image": "localhost/wadspaces-writing:latest", "display": "host",
            "env": {"PUID": "1000", "TZ": "Pacific/Fiji"}, "secrets": ["github_token"], "devices": ["/dev/dri"],
            "shm_size": "1g", "projects": [{"id": "p1", "kind": "github", "mount": "Notes", "repo": "HungGod/Notes"}],
        });
        let got = super::quadlet(&w, "/home/u/.local/state/wadspaces", Some(1000));
        assert_eq!(got, include_str!("../../../fixtures/quadlet/wad-writing-rootless.container"));
    }

    #[test]
    fn signins_are_mounted_with_the_extra_folder() {
        let w = json!({
            "id": "writing", "name": "Writing", "image": "localhost/wadspaces-writing:latest", "display": "host",
            "env": {"PUID": "1000"}, "shm_size": "1g",
            "signins": [
                {"id": "github-a1b2", "app": "github", "web": true, "path": "/var/lib/wadspaces-signins/github-a1b2"},
                {"id": "vscode-c3d4", "app": "vscode", "path": "/var/lib/wadspaces-signins/vscode-c3d4"},
            ],
        });
        let got = super::quadlet(&w, super::STATE_DIR, None);
        assert_eq!(got, include_str!("../../../fixtures/quadlet/wad-writing-signins.container"));
    }

    #[test]
    fn devices_wadd_attaches_may_be_opened_not_made() {
        let w = json!({
            "id": "writing", "name": "Writing", "image": "localhost/wadspaces-writing:latest", "display": "host",
            "devices": ["/dev/dri"], "device_rules": ["c 189:* rw", "c 241:* rw"],
            "drives_dir": "/run/wadspaces-drives/attached/writing",
        });
        let got = super::quadlet(&w, super::STATE_DIR, None);
        assert_eq!(got, include_str!("../../../fixtures/quadlet/wad-writing-devices.container"));
    }

    #[test]
    fn a_mount_is_the_machines_folder_read_write_and_never_relabelled() {
        let w = json!({
            "id": "writing", "name": "Writing", "image": "localhost/wadspaces-writing:latest", "display": "stream",
            "port": 3101, "env": {"PUID": "1000"},
            "projects": [
                {"id": "p1", "kind": "github", "mount": "Notes", "repo": "HungGod/Notes"},
                {"id": "mount-a1", "kind": "mount", "mount": "Thesis", "path": "/var/home/wad/Thesis"},
                {"id": "mount-b2", "kind": "mount", "mount": "Elsewhere"},
            ],
        });
        let got = super::quadlet(&w, super::STATE_DIR, None);
        assert_eq!(got, include_str!("../../../fixtures/quadlet/wad-writing-mount.container"));
        // Not on this machine: nothing to mount, and SELinux stays on for a streamed one.
        let mut away = w.clone();
        away["projects"][1].as_object_mut().unwrap().remove("path");
        let got = super::quadlet(&away, super::STATE_DIR, None);
        assert!(!got.contains("/config/Desktop") && !got.contains("SecurityLabelDisable"), "{got}");
    }
}
